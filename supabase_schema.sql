-- Setup Storage Security Policies (Allow Public Read & Write for Media)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' AND policyname = 'Public Access for attendance-media'
    ) THEN
        CREATE POLICY "Public Access for attendance-media"
        ON storage.objects FOR SELECT
        USING (bucket_id = 'attendance-media');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' AND policyname = 'Allow Uploads for attendance-media'
    ) THEN
        CREATE POLICY "Allow Uploads for attendance-media"
        ON storage.objects FOR INSERT
        WITH CHECK (bucket_id = 'attendance-media');
    END IF;
    
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' AND policyname = 'Allow Updates for attendance-media'
    ) THEN
        CREATE POLICY "Allow Updates for attendance-media"
        ON storage.objects FOR UPDATE
        USING (bucket_id = 'attendance-media');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' AND policyname = 'Allow Deletes for attendance-media'
    ) THEN
        CREATE POLICY "Allow Deletes for attendance-media"
        ON storage.objects FOR DELETE
        USING (bucket_id = 'attendance-media');
    END IF;
END $$;
