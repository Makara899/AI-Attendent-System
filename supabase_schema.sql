-- 1. Create Students Table
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    gender TEXT DEFAULT 'Other',
    major TEXT DEFAULT 'Computer Science',
    email TEXT,
    phone TEXT,
    class_name TEXT NOT NULL,
    photo_url TEXT,
    face_descriptor TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('Asia/Phnom_Penh', NOW())
);

-- 2. Create Sessions Table
CREATE TABLE IF NOT EXISTS public.sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_code TEXT,
    name TEXT NOT NULL,
    course_name TEXT NOT NULL,
    major TEXT DEFAULT 'Computer Science',
    lecturer TEXT DEFAULT 'Professor',
    room TEXT DEFAULT 'Room 101',
    class_name TEXT NOT NULL,
    session_date TEXT NOT NULL,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    status TEXT DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('Asia/Phnom_Penh', NOW())
);

-- 3. Create Attendance Table
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    session_id BIGINT NOT NULL REFERENCES public.sessions(id) ON DELETE CASCADE,
    date TEXT NOT NULL,
    check_in_time TEXT NOT NULL,
    status TEXT DEFAULT 'PRESENT',
    check_in_method TEXT DEFAULT 'AI_FACE',
    confidence_score DOUBLE PRECISION DEFAULT 1.0,
    snapshot_url TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('Asia/Phnom_Penh', NOW()),
    CONSTRAINT unique_student_session_date UNIQUE (student_id, session_id, date)
);

-- 4. Create System Logs Table
CREATE TABLE IF NOT EXISTS public.system_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('Asia/Phnom_Penh', NOW())
);

